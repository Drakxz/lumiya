const {createManager,createPanelServer}=require("../call-panel");
const {createStore}=require("../call-panel/store");
const CHANNEL="1571977809633615942";
function fixture(env={}){
  let saved=[];const sessions=[];
  const store={load:async()=>structuredClone(saved),save:async rows=>{saved=structuredClone(rows);}};
  const install=options=>{const s={options,audio:[],presences:[],closed:false,close(){this.closed=true;},setAudio(mute,deaf){this.audio.push({mute,deaf});},setPresence(p){this.presences.push(p);},getStatus:()=>({state:"connected"})};sessions.push(s);return s;};
  const manager=createManager({client:new EventEmitter(),store,env,install});
  return {manager,store,install,sessions};
}
test("accounts can be saved, connected, edited without revealing tokens and deleted",async t=>{
  const f=fixture();t.after(()=>f.manager.close());await f.manager.ready;
  await f.manager.save({name:"Minha conta",channelId:CHANNEL,token:"private-token"});
  const a=f.manager.list()[0];
  assert.equal(a.enabled,false);assert.equal(a.token,undefined);assert.equal(a.hasToken,true);
  assert.equal(f.sessions.length,0);
  await f.manager.action(a.id,"connect");assert.equal(f.sessions.length,1);
  assert.equal(f.sessions[0].options.token,"private-token");
  assert.equal(f.sessions[0].options.manageSignals,false);
  await f.manager.save({id:a.id,name:"Editada",channelId:CHANNEL,token:""});
  assert.equal(f.sessions[0].closed,true);assert.equal(f.sessions[1].options.token,"private-token");
  await assert.rejects(f.manager.save({name:"Repetida",channelId:CHANNEL,token:"private-token"}));
  await assert.rejects(f.manager.save({name:"Inválida",channelId:"123",token:"another"}));
  await f.manager.action(a.id,"disconnect");assert.equal(f.sessions[1].closed,true);
  await f.manager.action(a.id,"delete");assert.equal(f.manager.list().length,0);
});
