test("local panel requires access key, rejects foreign origins and never returns tokens",async t=>{
  const f=fixture();await f.manager.ready;t.after(()=>f.manager.close());
  await f.manager.save({name:"Conta",channelId:CHANNEL,token:"super-secret-token"});
  const panel=createPanelServer({manager:f.manager,html:"<!doctype html><title>Painel</title>",accessKey:"a".repeat(64)});
  const url=await panel.listen(0);t.after(()=>new Promise(resolve=>panel.server.close(resolve)));
  const base=new URL(url).origin,headers={"X-Panel-Key":"a".repeat(64)};
  assert.equal((await fetch(`${base}/api/accounts`)).status,401);
  assert.equal((await fetch(`${base}/api/accounts`,{headers:{"X-Panel-Key":"é".repeat(64)}})).status,401);
  assert.equal((await fetch(`${base}/api/accounts`,{headers:{...headers,Origin:"https://evil.example"}})).status,403);
  const response=await fetch(`${base}/api/accounts`,{headers});
  assert.equal(response.status,200);assert.doesNotMatch(await response.text(),/super-secret-token/);
  const exported=await fetch(`${base}/api/export`,{headers});
  const exportBody=await exported.json();
  assert.equal(exportBody.accounts[0].name,"Conta");
  assert.doesNotMatch(JSON.stringify(exportBody),/super-secret-token|hasToken|profile|userId/);
  assert.equal((await fetch(`${base}/api/export`)).status,401);
  const html=await fetch(base);
  assert.match(html.headers.get("content-security-policy"),/frame-ancestors 'none'/);
  assert.match(panel.server.address().address,/127\.0\.0\.1/);
});
