test("authenticated upload goes through the actual backend queue; member and admin pages work",async({page,context})=>{
  test.setTimeout(60000);
  await context.addCookies([{name:"iw_session",value:test.info().project.name==="mobile"?"browser-test-only-mobile-session":"browser-test-only-session",url:"http://127.0.0.1:3111",httpOnly:true,sameSite:"Lax"}]);
  await page.goto("/app");
  await expect(page.getByRole("heading",{name:"Onde você quer postar?"})).toBeVisible();
  await expect(page.getByRole("button",{name:"Escolher Clube dos Criadores",exact:true})).toBeVisible();
  await page.screenshot({path:test.info().outputPath("choose-server.png"),fullPage:true});
  await page.getByRole("button",{name:"Escolher GRIFE",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Olá, Camila."})).toBeVisible();
  await expect(page.getByRole("heading",{name:"Os melhores momentos merecem companhia."})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:test.info().outputPath("dashboard.png"),fullPage:true});
  await page.getByRole("button",{name:"Criar publicação"}).click();
  await expect(page.getByRole("heading",{name:"Nova publicação",exact:true})).toBeVisible();
  // Generate a valid PNG with Sharp (the handcrafted tiny fixtures vary in decoder validity).
  const {createRequire}=await import("node:module");
  const require=createRequire(import.meta.url);
  const buffer=await require("sharp")({create:{width:120+Math.floor(Math.random()*100),height:100,channels:3,background:"#"+Math.floor(Math.random()*16777215).toString(16).padStart(6,"0")}}).png().toBuffer();
  await page.locator('input[type="file"]').setInputFiles({name:"momento.png",mimeType:"image/png",buffer});
  await page.getByLabel("Legenda").fill("Um momento da comunidade");
  await page.getByLabel("Tenho autorização", {exact:false}).check();
  await page.getByRole("button",{name:"Publicar na comunidade"}).click();
  await expect(page.getByRole("heading",{name:"Minhas publicações",exact:true})).toBeVisible();
  await expect(page.getByRole("article").first().getByText("Um momento da comunidade",{exact:true})).toBeVisible();
  await expect(page.getByRole("article").first().getByText("Publicada",{exact:true})).toBeVisible({timeout:20000});
  const published=page.getByRole("article").first();
  const photo=published.getByRole("img",{name:"Fotografia 1 da publicação"});
  await expect(photo).toBeVisible();
  await expect.poll(()=>photo.evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(0);
  await published.getByRole("button",{name:"Ver prévia no Discord"}).click();
  await expect(published.locator(".discord-preview")).toBeVisible();
  await expect(published.locator(".discord-preview").getByText("Um momento da comunidade",{exact:false})).toBeVisible();
  await published.getByRole("button",{name:"Fechar prévia"}).click();
  await expect(published.locator(".discord-preview")).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  if(await page.getByRole("button",{name:"Abrir menu"}).isVisible())await page.getByRole("button",{name:"Abrir menu"}).click();
  await page.getByRole("button",{name:"Administração",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Administração",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Configurações",exact:true}).click();
  await expect(page.getByRole("combobox",{name:"Canal de Instagram",exact:true})).toBeVisible();
  await page.screenshot({path:test.info().outputPath("settings.png"),fullPage:true});
  await page.getByLabel("Qual servidor você quer gerenciar?").selectOption("200000000000000001");
  const channelSelect=page.getByRole("combobox",{name:"Canal de Instagram",exact:true});
  await expect(channelSelect).toBeVisible();
  await expect(channelSelect.locator("option")).toHaveText(["Selecione um canal deste servidor","#insta-criadores"]);
  await channelSelect.selectOption("200000000000000003");
  await page.getByLabel("Nome do site",{exact:true}).fill("Criadores");
  await page.getByRole("button",{name:"Salvar configurações",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Configurações de Clube dos Criadores salvas.");
  await page.getByLabel("Qual servidor você quer gerenciar?").selectOption("100000000000000001");
  await page.getByRole("button",{name:"Configurações",exact:true}).click();
  await expect(channelSelect).toHaveValue("100000000000000003");
  await expect(page.getByLabel("Nome do site",{exact:true})).not.toHaveValue("Criadores");
  await page.getByLabel("Qual servidor você quer gerenciar?").selectOption("200000000000000001");
  await expect(channelSelect).toHaveValue("200000000000000003");
  await expect(page.getByLabel("Nome do site",{exact:true})).toHaveValue("Criadores");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:test.info().outputPath("guild-settings.png"),fullPage:true});
  await page.getByRole("button",{name:"Trocar servidor",exact:true}).click();
  await page.getByRole("button",{name:"Escolher Clube dos Criadores",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Olá, Camila."})).toBeVisible();
  await expect(page.getByRole("article").filter({hasText:"Um momento da comunidade"})).toHaveCount(0);
  await page.getByRole("button",{name:"Criar publicação",exact:true}).click();
  await expect(page.locator(".posting-destination")).toContainText("Clube dos Criadores");
  await page.locator('input[type="file"]').setInputFiles({name:"outro-momento.png",mimeType:"image/png",buffer});
  await page.getByLabel("Legenda").fill("Momento no Clube dos Criadores");
  await page.getByLabel("Tenho autorização",{exact:false}).check();
  await page.getByRole("button",{name:"Publicar na comunidade"}).click();
  const otherPost=page.getByRole("article").filter({hasText:"Momento no Clube dos Criadores"}).first();
  await expect(otherPost.getByText("Publicada",{exact:true})).toBeVisible({timeout:20000});
  await expect(otherPost.getByRole("link",{name:"Ver no Discord"})).toHaveAttribute("href",/channels\/200000000000000001\/200000000000000003\//);
  await expect(otherPost.getByRole("img",{name:"Fotografia 1 da publicação"})).toBeVisible();
  await page.getByRole("button",{name:"Trocar servidor",exact:true}).click();
  await page.getByRole("button",{name:"Escolher GRIFE",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Olá, Camila."})).toBeVisible();
  await expect(page.getByRole("article").filter({hasText:"Momento no Clube dos Criadores"})).toHaveCount(0);
  await expect(page.getByRole("article").filter({hasText:"Um momento da comunidade"}).first()).toBeVisible();
});
