import {test,expect} from "../frontend/node_modules/@playwright/test/index.mjs";
test("ordinary members choose a shared server without administrative permissions",async({page,context})=>{
  await context.addCookies([{name:"iw_session",value:"browser-test-only-member-session",url:"http://127.0.0.1:3111",httpOnly:true,sameSite:"Lax"}]);
  await page.goto("/app");
  await expect(page.getByRole("heading",{name:"Onde você quer postar?"})).toBeVisible();
  await expect(page.getByRole("button",{name:"Escolher Clube dos Criadores",exact:true})).toBeVisible();
  await expect(page.locator(".server-choice-card .badge")).toHaveCount(0);
  await page.getByRole("button",{name:"Escolher GRIFE",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Olá, Camila."})).toBeVisible();
  if(await page.getByRole("button",{name:"Abrir menu"}).isVisible())await page.getByRole("button",{name:"Abrir menu"}).click();
  await expect(page.getByRole("button",{name:"Administração",exact:true})).toHaveCount(0);
  await page.locator(".sidebar").getByRole("button",{name:/^Nova publicação/}).click();
  await expect(page.locator(".posting-destination")).toContainText("GRIFE");
});
